#!/usr/bin/env python3
"""Pre-rendered frames -> retro sprite sheet.

Box-reduces the 4x Blender renders to 176x176, builds ONE palette per character
(32 colours = two 16-colour arcade palettes) from all frames together, snaps every
frame to it without dithering, hard alpha, 1-px dark outline; writes f_<char>.png
and f_<char>.lua (hurt boxes from the pixels, hit points from tips.json).

usage: post3d.py RENDERDIR OUTDIR char [--colors 32] [--poses a,b,c]
"""
import argparse
import json
import os
import sys

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import mkassets as M  # noqa: E402
import mkfighters as F  # noqa: E402

FS, OX, OY, COLS = 176, 88, 172, 8
OL = (28, 18, 20)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('renders')
    ap.add_argument('out')
    ap.add_argument('char')
    ap.add_argument('--colors', type=int, default=32)
    ap.add_argument('--poses')
    a = ap.parse_args()
    src = os.path.join(a.renders, a.char)
    poses = dict(F.POSES)
    if a.char == 'toro':
        poses.update(F.TORO_EXTRA)
    names = a.poses.split(',') if a.poses else list(poses)
    small = []
    for n in names:
        im = Image.open(os.path.join(src, n + '.png')).convert('RGBA')
        arr = np.array(im).astype(float)
        arr[..., :3] *= arr[..., 3:4] / 255                     # premultiplied box filter
        r = np.array(Image.fromarray(arr.astype(np.uint8)).resize((FS, FS), Image.BOX)).astype(float)
        r[..., :3] /= np.maximum(r[..., 3:4], 1) / 255
        r = np.clip(r, 0, 255).astype(np.uint8)
        r[..., 3] = np.where(r[..., 3] > 120, 255, 0)
        small.append(r)
    # one palette for the whole character (outline colour reserved)
    px = np.concatenate([s[s[..., 3] > 0][:, :3] for s in small])
    strip = Image.fromarray(px.reshape(1, -1, 3))
    pal_img = strip.quantize(colors=a.colors - 1, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = np.array(pal_img.getpalette()[:3 * (a.colors - 1)]).reshape(-1, 3)
    pal_full = [tuple(int(v) for v in c) for c in pal] + [OL]
    tips = json.load(open(os.path.join(src, 'tips.json')))
    rows = (len(names) + COLS - 1) // COLS
    sheet = Image.new('RGBA', (FS * COLS, FS * rows), (0, 0, 0, 0))
    lua = ['-- generated by tools/post3d.py from the Blender renders (origin = feet, facing right)',
           'return {', '    size = %d, ox = %d, oy = %d, cols = %d,' % (FS, OX, OY, COLS)]
    for i, (n, s) in enumerate(zip(names, small)):
        im = M.quantize_to(Image.fromarray(s), pal_full[:-1])
        im = M.outline(im, OL)
        sheet.alpha_composite(im, ((i % COLS) * FS, (i // COLS) * FS))
        al = np.array(im)[..., 3] > 0
        ys, xs = np.nonzero(al)
        hurt = (int(xs.min()) - OX, int(ys.min()) - OY, int(xs.max()) - OX, int(ys.max()) - OY)
        t = tips.get(n)
        hs = 'nil' if not t else '{ %d, %d, 9 }' % tuple(t)
        lua.append('    %s = { i = %d, hurt = { %d, %d, %d, %d }, hit = %s },' % ((n, i) + hurt + (hs,)))
    lua.append('}')
    M.OUT = a.out
    M.save(sheet, f'f_{a.char}.png', maxcol=a.colors)
    with open(os.path.join(a.out, f'f_{a.char}.lua'), 'w') as f:
        f.write('\n'.join(lua) + '\n')


if __name__ == '__main__':
    main()
