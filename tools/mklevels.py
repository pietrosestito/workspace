#!/usr/bin/env python3
"""Convert the ASCII level maps in levels/ into ca65 data (levels.inc).

Map format: 15 lines, one char per 16x16 cell, all lines the same length.
  .  sky            #  ground (must be a solid column starting from the bottom)
  B  brick block (at most one per column, above the ground)
  o  coin           w  walker enemy     s  spiky enemy (cannot be stomped)
  K  boss (top-left cell of the 32x32 boss, place it 2 rows above the ground)

Each column becomes one byte: low nibble = ground height, high nibble = brick row.
Objects become (column, row, type) triplets sorted by column, terminated by $FF.
"""
import glob
import os
import sys

ROWS = 15
OBJ_TYPES = {'o': 1, 'w': 2, 's': 3, 'K': 4}
MAX_WIDTH = 240


def fail(path, msg):
    sys.exit(f"{path}: {msg}")


def convert(path):
    with open(path) as f:
        lines = [l.rstrip('\n') for l in f if l.strip()]
    if len(lines) != ROWS:
        fail(path, f"expected {ROWS} lines, got {len(lines)}")
    width = len(lines[0])
    if any(len(l) != width for l in lines):
        fail(path, "all lines must have the same length")
    if not 17 <= width <= MAX_WIDTH:
        fail(path, f"width must be 17..{MAX_WIDTH} columns, got {width}")

    cols, objs = [], []
    for c in range(width):
        column = [lines[r][c] for r in range(ROWS)]
        height = 0
        while height < ROWS and column[ROWS - 1 - height] == '#':
            height += 1
        if '#' in column[:ROWS - height]:
            fail(path, f"column {c}: ground must be contiguous from the bottom")
        bricks = [r for r in range(ROWS) if column[r] == 'B']
        if len(bricks) > 1:
            fail(path, f"column {c}: at most one brick per column")
        brick = bricks[0] if bricks else 0
        if brick == 0 and bricks:
            fail(path, f"column {c}: bricks are not allowed on row 0")
        cols.append(height | (brick << 4))
        for r, ch in enumerate(column):
            if ch in OBJ_TYPES:
                objs.append((c, r, OBJ_TYPES[ch]))
            elif ch not in '.#B':
                fail(path, f"unknown char {ch!r} at column {c}, row {r}")
    objs.sort()
    return width, cols, objs


def main():
    src_dir, out = sys.argv[1], sys.argv[2]
    paths = sorted(glob.glob(os.path.join(src_dir, 'level*.txt')))
    if not paths:
        sys.exit("no levels found")
    out_lines = ["; generated by tools/mklevels.py - do not edit", f"LEVEL_COUNT = {len(paths)}", ""]
    widths = []
    for i, p in enumerate(paths):
        width, cols, objs = convert(p)
        widths.append(width)
        out_lines.append(f"level{i}_cols:")
        for j in range(0, len(cols), 16):
            out_lines.append("  .byte " + ",".join(f"${b:02X}" for b in cols[j:j + 16]))
        out_lines.append(f"level{i}_objs:")
        for c, r, t in objs:
            out_lines.append(f"  .byte {c},{r},{t}")
        out_lines.append("  .byte $FF")
    n = len(paths)
    out_lines.append("level_cols_lo: .byte " + ",".join(f"<level{i}_cols" for i in range(n)))
    out_lines.append("level_cols_hi: .byte " + ",".join(f">level{i}_cols" for i in range(n)))
    out_lines.append("level_objs_lo: .byte " + ",".join(f"<level{i}_objs" for i in range(n)))
    out_lines.append("level_objs_hi: .byte " + ",".join(f">level{i}_objs" for i in range(n)))
    out_lines.append("level_width:   .byte " + ",".join(str(w) for w in widths))
    with open(out, 'w') as f:
        f.write("\n".join(out_lines) + "\n")


if __name__ == '__main__':
    main()
