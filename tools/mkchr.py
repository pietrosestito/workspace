def parse(art, w, h):
    rows = [r for r in art.split('\n') if r]
    if len(rows) != h:
        raise SystemExit(f"art has {len(rows)} rows, expected {h}:\n{art}")
    out = []
    for r in rows:
        if len(r) > w:
            raise SystemExit(f"row too long ({len(r)} > {w}): {r!r}")
        out.append([0 if ch == '.' else int(ch) for ch in r.ljust(w, '.')])
    return out


def encode(pixels):
    """8x8 pixel grid -> 16 bytes NES 2bpp tile."""
    lo = [sum(((pixels[y][x] & 1) << (7 - x)) for x in range(8)) for y in range(8)]
    hi = [sum(((pixels[y][x] >> 1) << (7 - x)) for x in range(8)) for y in range(8)]
    return bytes(lo + hi)


class Table:
    def __init__(self):
        self.data = bytearray(4096)
        self.used = set()

    def put(self, index, art, wt, ht):
        px = parse(art, wt * 8, ht * 8)
        for ty in range(ht):
            for tx in range(wt):
                t = index + ty * wt + tx
                if t in self.used:
                    raise SystemExit(f"tile ${t:02X} used twice")
                self.used.add(t)
                tile = [row[tx * 8:tx * 8 + 8] for row in px[ty * 8:ty * 8 + 8]]
                self.data[t * 16:t * 16 + 16] = encode(tile)

    def put_font(self):
        for ch, glyph in FONT.items():
            rows = glyph.split()
            art = "\n".join("." + r.replace('#', '3') + ".." for r in rows) + "\n........"
            self.put(ord(ch), art, 1, 1)


def halves(art):
    rows = [r for r in art.split('\n') if r]
    return "\n".join(r[:16] for r in rows), "\n".join(r[16:] for r in rows)


